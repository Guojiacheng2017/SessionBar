import assert from "node:assert/strict";
import { existsSync, mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import test from "node:test";
import { piExtensionSource, setupPiHooks, teardownPiHooks } from "../dist/hooks/hookManager.js";

test("Pi extension reports lifecycle, tool, and compaction events without polling", () => {
  const source = piExtensionSource("/tmp/Session Bar/report.sh");
  for (const event of [
    "session_start",
    "before_agent_start",
    "agent_start",
    "tool_execution_start",
    "tool_execution_end",
    "session_before_compact",
    "session_compact",
    "agent_settled",
    "session_shutdown",
  ]) assert.match(source, new RegExp(`pi\\.on\\(\\"${event}\\"`));
  assert.match(source, /SESSIONBAR_AGENT: "pi"/);
  assert.match(source, /SESSIONBAR_SESSION_TYPE: "Pi Agent"/);
  assert.match(source, /SESSIONBAR_SESSION_ID/);
  assert.match(source, /SESSIONBAR_CONTEXT_PERCENT/);
  assert.match(source, /spawn\(reportPath, \[status, task\]/);
  assert.doesNotMatch(source, /setInterval|setTimeout|exec\(|shell:\s*true/);
  assert.doesNotMatch(source, /event\.prompt|user: /);
  assert.match(source, /"before_agent_start", "working", "Handling prompt"/);
});

test("Pi extension setup is idempotent and teardown removes only SessionBar's file", () => {
  const root = mkdtempSync(join(tmpdir(), "sessionbar-pi-"));
  const previous = process.cwd();
  process.chdir(root);
  try {
    const first = setupPiHooks(false, "/tmp/report.sh");
    assert.equal(first.added, 1);
    assert.equal(first.path, join(process.cwd(), ".pi", "extensions", "sessionbar.ts"));
    assert.match(readFileSync(first.path, "utf8"), /Generated by SessionBar/);
    assert.equal(setupPiHooks(false, "/tmp/report.sh").added, 0);

    const unrelated = join(root, ".pi", "extensions", "other.ts");
    writeFileSync(unrelated, "export default () => {};\n");
    assert.equal(teardownPiHooks(false), 1);
    assert.equal(existsSync(first.path), false);
    assert.equal(existsSync(unrelated), true);
  } finally {
    process.chdir(previous);
  }
});
